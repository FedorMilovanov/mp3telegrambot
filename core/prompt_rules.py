#!/usr/bin/env python3
"""
prompt_rules.py — Общие константы форматирования для всех Gemini-промптов.

Единственный источник истины для правил которые повторялись в SYNOPSIS,
SYNOPSIS_QA, STUDY_ANALYSIS и REFLECTION_APPLICATION промптах.

Используется через подстановку: {INLINE_TIMESTAMP_RULES}, {STRICT_BANS} и т.д.
Промпты включают эти блоки вместо дублирования.
"""

# ─── Правила inline-таймкодов ────────────────────────────────────────────────
# Повторялось в SYNOPSIS (L1047), SYNOPSIS_QA (L1320), STUDY (L2402),
# REFLECTION (L2866) — 4 раза, ~18 строк каждый.

INLINE_TIMESTAMP_RULES = """\
ПРАВИЛО INLINE-ТАЙМКОДОВ:
Когда в content нужно сослаться на конкретный момент видео — пиши строго так:
⏱ **M:SS** или 📌 **M:SS**
Примеры: ⏱ **22:15**, 📌 **40:30**, ⏱ **1:05:42**
Никаких скобок, никакого текста рядом с числами внутри **, только время.
Система автоматически превратит это в кликабельную ссылку.

КРИТИЧЕСКИ ВАЖНО — ПОЗИЦИЯ ТАЙМКОДА:
Таймкод ВСЕГДА стоит ВНУТРИ предложения — ПЕРЕД точкой, не после.
❌ Плохо: Когда отношения налаживались. ⏱ **17:30** ← точка до таймкода
✅ Хорошо: Когда отношения налаживались ⏱ **17:30**.
НИКОГДА не начинай предложение или абзац с таймкода.\
"""

# ─── Строгие запреты (клише) ─────────────────────────────────────────────────
# Повторялось в SYNOPSIS (L1079) и STUDY (L1345) — 16 общих фраз.
# REFLECTION имеет свой список, но с пересечением ~10 фраз.

STRICT_BANS = """\
СТРОГИЕ ЗАПРЕТЫ — НЕ ПИСАТЬ:
- «главная мысль», «ключевой тезис состоит в том»
- «важно понять», «следует отметить», «это показывает»
- «таким образом», «в итоге», «из этого следует»
- «почему это важно», «здесь видно», «этот раздел показывает»
- «автор подчеркивает», «проповедник говорит о том, что»
- «спикер отмечает», «он сказал», «автор считает»
- «**В материале:**» — шаблон STUDY-досье, в конспекте запрещён

Не подводить выводы от себя.
Не добавлять мораль и application если их нет в речи автора.
Не писать как редактор статьи.
Не использовать конструкции от третьего лица.\
"""

# ─── Правило имени автора ────────────────────────────────────────────────────
# Повторялось в аудио-анализе и в нескольких подсказках к промптам.

AUTHOR_NAMING_RULE = """\
ИМЯ АВТОРА:
Только фамилия или «Имя Фамилия» — без титулов «пастор», «д-р», «брат».
Если имя неизвестно — оставь поле пустым, не пиши «автор» или «проповедник».\
"""

# ─── Правило JSON-вывода ─────────────────────────────────────────────────────
# Используется в хвосте каждого промпта.

JSON_OUTPUT_RULE = """\
Верни только чистый JSON — без ```json, без пояснений до или после.\
"""

