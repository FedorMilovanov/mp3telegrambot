# ─── Правило таймкодов для QA-конспекта ─────────────────────────────────────
# Специфично для SYNOPSIS_PROMPT_QA — таймкоды привязаны к section.time.

QA_TIMESTAMP_RULE = """ПРАВИЛО ТАЙМКОДОВ ОТНОСИТЕЛЬНО СЕКЦИИ:
Таймкод внутри content НИКОГДА не должен указывать на время ДО начала этой секции (section.time).
Если section.time = "8:30", ни один таймкод в content не может быть раньше 8:30.
Использование таймкода из предыдущей секции означает, что часть ответа перепутана:
перепроверь принадлежность каждого момента перед вставкой таймкода.

Формат таймкода: ⏱ **M:SS** — всегда внутри предложения ПЕРЕД точкой, не после.
Пробел обязателен: ⏱ **7:30**, не ⏱**7:30**. Таймкод ВНЕ *курсива* и **жирного**.
НИКОГДА не начинай предложение или абзац с таймкода."""


