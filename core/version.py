#!/usr/bin/env python3
"""Единственный источник версии проекта.

Версия объявлена здесь, а не в ``pyproject.toml``: setuptools читает её через
``attr`` (``dynamic = ["version"]``), поэтому установленный пакет и работающий
код всегда показывают одно и то же число. Читать её из кода дешевле, чем
парсить ``pyproject.toml`` в рантайме.

Правила повышения — SemVer:

* ``MAJOR`` — несовместимое изменение формата данных или конфигурации
  (например, миграция схемы БД без обратного пути);
* ``MINOR`` — новая функциональность;
* ``PATCH`` — исправления без новых возможностей.

Изменение версии обязано сопровождаться записью в ``CHANGELOG.md``.
"""

from __future__ import annotations

__version__ = "4.0.0"

#: Версия схемы, ожидаемая от ``pyproject.toml``/``requirements.txt`` при
#: проверке согласованности в ``tests/test_packaging_metadata.py``.
__all__ = ["__version__"]
