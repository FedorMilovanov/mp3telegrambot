    r"ignore\s+(?:all\s+)?(?:previous|above|earlier|prior|preceding)\s+instructions?|"
    r"disregard\s+(?:all\s+)?(?:previous|above|earlier|prior|preceding)\s+instructions?|"
    r"forget\s+(?:all\s+)?(?:previous|above|earlier|everything)\b|"
