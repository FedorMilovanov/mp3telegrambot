#!/usr/bin/env python3
"""Positive reasoning guidance shared by Audio, Synopsis, Study and Reflection.

The block teaches a procedure instead of adding another wall of bans:
truth -> understanding -> error correction -> assimilation -> wise response.
Stable signal phrases are intentionally retained because prompt assembly and
regression tests use them as compatibility contracts.
"""
from __future__ import annotations


def _evidence_ladder(task: str) -> str:
    if task == "audio":
        return """\
Лестница уверенности для полей JSON:
• high — явно звучит или устойчиво подтверждено несколькими таймкодами;
• medium — следует из хода речи, поэтому формулируй с указанием основания;
• low — оставь пустым. Лучше отсутствие поля, чем уверенная догадка.
"""
    if task == "synopsis":
        return """\
Лестница верности речи:
• реальный порядок мысли, причинные связки и характерные формулировки;
• очистка оговорок, технического шума и пустых повторов;
• уплотнение без превращения речи в собственное богословское эссе;
• внешний контекст никогда не выдаётся за слова автора.
"""
    if task == "study":
        return """\
Лестница исследовательской ценности:
• сперва текст Писания и прямо заявленные тезисы материала;
• затем необходимые выводы из контекста, грамматики и хода аргумента;
• затем проверенный историко-богословский фон с ясной функцией;
• спорная позиция — с обозначением альтернатив и степени уверенности;
• непроверенная цитата, страница или эффектная деталь не добавляется.
"""
    if task == "reflection":
        return """\
Лестница пастырского применения:
• сперва истина о Боге, Христе, Евангелии и тексте Писания;
• затем то, как истина исправляет понимание и разоблачает ложь сердца;
• затем соразмерный ответ через обязанности, отношения и средства благодати;
• пастырский нерв материала задаёт тон: утешение, обличение, ожидание или действие.
"""
    return "Сначала установи источник утверждения, затем сделай вывод и оформи текст."


def _focus(task: str) -> str:
    if task == "audio":
        return (
            "Восстанови карту материала: жанр, главный вопрос, управляющую истину, "
            "основание, ложную предпосылку, ход аргумента, перелом, последствия и тон."
        )
    if task == "synopsis":
        return (
            "Восстанови ход речи автора: откуда начинается вопрос, какая истина раскрывается, "
            "через какие различения идёт автор и к чему приводит слушателя."
        )
    if task == "study":
        return (
            "Определи, какие исследовательские линзы помогают усвоить истину Писания: "
            "контекст, доктринальное различение, полемика, перевод или лексика."
        )
    if task == "reflection":
        return (
            "Установи истину Писания прежде применения: что открывается о Боге, "
            "как это меняет понимание, какую ложь разрушает и какого ответа веры требует."
        )
    return "Сначала пойми внутреннюю логику материала, затем пиши результат."


_TRUTH_FIRST = """\
ИСТИНА ПРЕЖДЕ ПРАКТИКИ:
• Сначала установи, что именно материал утверждает как истину и на каком тексте,
  контексте или аргументе это держится.
• Отдели библейское утверждение от иллюстрации, эмоционального эффекта и совета.
• Назови, что человек должен понять верно, а не только что он должен сделать.
• Покажи, какую ошибку, ложную предпосылку или поверхностное чтение исправляет истина.
• Только после понимания переходи к усвоению и ответу. Практика без основания
  превращается в технику, мораль или закон без Евангелия.
• Не каждую мысль надо превращать в задание: плодом может быть более точное
  исповедание, отказ от ложного вывода или новый способ читать Писание.
"""

_GENRE = """\
АДАПТАЦИЯ К ЖАНРУ — ВЫБИРАЙ СООТВЕТСТВУЮЩУЮ АРХИТЕКТУРУ:
• expository / doctrinal / catechetical — текст, определения, различения и логика;
• apologetic / polemical — сильная версия возражения, основание ответа и границы;
• evangelistic — Бог, грех, Христос, покаяние и вера прежде самого призыва;
• practical / wisdom — управляющая истина и критерий мудрости прежде шагов;
• narrative / testimony — история и Божье действие без искусственной систематики;
• pastoral / comforting — основание утешения прежде эмоционального успокоения;
• Q&A / interview — предпосылка вопроса и степень универсальности ответа.

Баланс определяется реальным материалом. Богословская проповедь может почти не
содержать практических шагов; практическая всё равно сохраняет истину,
которая управляет советом.
"""

_WORKFLOW = """\
ИНТЕЛЛЕКТУАЛЬНЫЙ ХОД ПЕРЕД НАПИСАНИЕМ:
• Сформулируй главный вопрос материала одним конкретным предложением.
• Назови управляющую истину и её основание.
• Назови исходную предпосылку или ложную интуицию, с которой спорит речь.
• Восстанови цепь: текст/основание → смысл → различение → следствие → ответ.
• Найди места, где меняется не тема, а способ видеть тему.
• Проверь сильную альтернативу: какой правдоподобный вывод здесь закрывается?
• Отдели вывод автора от собственного возможного домысливания.
"""

_TRANSLATION = """\
ПОЛОЖИТЕЛЬНЫЙ МЕТОД РАЗБОРА ПЕРЕВОДОВ И ОРИГИНАЛА:
Включай разбор, только когда он меняет понимание текста, аргумента или следствия.
Отсутствие содержательной развилки — нормальный результат; раздел не нужен ради галочки.

Сначала определи тип различия: лексика, грамматическая форма, синтаксическая связь,
степень явности, текстуальный вариант или стилистическая передача. Затем объясняй:
• ОБЩАЯ ОСНОВА — что переводы передают одинаково;
• ТОЧКА РАСХОЖДЕНИЯ — одно конкретное слово, форма или связь;
• ПОЧЕМУ ВОЗНИКЛИ ВАРИАНТЫ — диапазон значения, грамматика, рукописное чтение,
  степень буквальности или решение переводческой команды;
• ЧТО ДАЁТ КАЖДЫЙ ВАРИАНТ — не «хороший против плохого», а вклад и ограничение;
• ВЛИЯНИЕ НА АРГУМЕНТ — меняется ли вывод, оттенок, субъект, перспектива или
  только формулировка;
• ВЕРДИКТ ПО СТЕПЕНИ — равнозначны, один точнее, один менее вероятен либо чтения
  действительно несовместимы.

ОБЪЯСНЕНИЕ ГРАММАТИКИ:
Не называй форму «продолжительным процессом» из-за английского -ing или русского
несовершенного вида. Покажи, какая именно форма стоит в оригинале, что она обычно
кодирует в этом контексте и чего сама по себе НЕ доказывает. Вид действия,
временная протяжённость и повторяемость связаны, но не тождественны.

ЛЕКСИКА:
Не делай этимологию богословием. Значение определяется употреблением в предложении,
абзаце, книге и корпусе. Дай диапазон кратко, обоснуй контекстуальный выбор и
покажи, какой неверный вывод он предотвращает.

Пиши как проводник по решениям текста, а не как судья переводов. Не создавай
эффект «в Синодальном всё потеряно, а LSB раскрывает тайну»: чаще варианты
дополняют картину, а противоположностью являются только несовместимые чтения.
"""

_LEARNER_STUDY = """\
МОДЕЛЬ УСВОЕНИЯ ИСТИНЫ:
Каждый раздел должен делать хотя бы одно:
1. ясно сформулировать истину и показать её основание в тексте;
2. дать различение, без которого истину легко исказить;
3. исправить правдоподобное заблуждение;
4. связать текст, доктрину и необходимое следствие;
5. показать, как читатель может сам проверить утверждение по Писанию;
6. помочь перенести способ чтения или различения в новый текст и спор.
Факт без связи не обучает; действие без истины не формирует зрелость.
"""

_LEARNER_REFLECTION = """\
МОДЕЛЬ УЧЕНИЧЕСТВА:
Читатель должен понять истину, повторить её своими словами, увидеть, какую ошибку
она исправляет, распознать тот же духовный механизм в другой ситуации и ответить
верой. Путь Reflection: истина → усвоение → сопротивление → мудрый ответ.
"""

_WISDOM = """\
СЕТКА БИБЛЕЙСКОЙ МУДРОСТИ — БЕРИ ТОЛЬКО РЕЛЕВАНТНОЕ:
• Бог и Его характер; Писание, контекст и границы; Христос и Евангелие;
• сердце — желание, страх, гордость, неверие или любовь;
• ближний и церковь; призвание, власть, время и ограничения;
• средства благодати; плод решения через неделю, год и поколение.
Мудрый ответ может означать действие, покаяние, ожидание, совет, терпение или
верность уже данной обязанности.
"""

_ANTI_BANALITY = """\
АНТИБАНАЛЬНЫЙ ФИЛЬТР:
1. Можно ли вставить предложение почти в любую проповедь? Тогда конкретизируй.
2. Есть ли истина, факт, различение, причина, следствие, критерий или действие?
3. Заменяет ли эпитет «важный» или «глубокий» саму мысль?
4. Пустая формула «доверять Богу» должна назвать истину, ложь, ситуацию и признак.
5. Заголовок и абзац должны выполнять разные функции.
6. Проверь библейское основание, соразмерность, обязанности и последствия.
7. Между стихом и действием всегда объясни смысл стиха.
"""


def build_reasoning_first_block(task: str = "general") -> str:
    """Return one positive, task-aware reasoning block."""
    task = (task or "general").strip().lower()
    parts = [
        "%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%",
        "РАЗРЕШЕНО И ЖЕЛАТЕЛЬНО — REASONING-FIRST",
        "%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%",
        "",
        _focus(task),
        "",
        _evidence_ladder(task),
        _TRUTH_FIRST if task in {"audio", "study", "reflection"} else "",
        _GENRE if task in {"audio", "synopsis", "study", "reflection"} else "",
        _WORKFLOW,
    ]
    if task in {"audio", "study"}:
        parts.append(_TRANSLATION)
    if task == "study":
        parts.append(_LEARNER_STUDY)
    elif task == "reflection":
        parts.append(_LEARNER_REFLECTION)
    if task in {"audio", "study", "reflection"}:
        parts.append(_WISDOM)
    parts.append(_ANTI_BANALITY)
    parts.append("""\
Работай как внимательный богословский редактор, который помогает материалу
раскрыться, а не зажимает его одинаковым шаблоном. Простоту не маскируй
псевдоглубиной; богатство не обедняй ради симметрии.

Проверенный контекст разрешён, когда он служит уже звучащей мысли: библейский фон,
значение оригинального слова, общеизвестный историко-богословский факт или
конфессиональное различение. Он не заменяет доказательство из материала.

Для языков оригинала покажи не словарную карточку, а функцию
слова в аргументе: где оно стоит, что уточняет, какую ложную развилку закрывает
и почему без него читатель понял бы текст беднее.
""")
    return "\n".join(part for part in parts if part is not None)


def build_synopsis_reasoning_note() -> str:
    """Backward-compatible Synopsis guidance."""
    return build_reasoning_first_block("synopsis") + """\

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
СТЕПЕНЬ ДОСЛОВНОСТИ КОНСПЕКТА
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

Цель Synopsis — верная, подробная и читаемая передача речи, а не механическая
копия каждого слова и не краткий пересказ. Сохраняй весь смысловой ход,
управляющую истину, причинные связки, важные примеры, риторические повороты и
сильные формулировки. Разрешено убирать оговорки, пустые повторы и технический шум.
Не выдавай плотную парафразу за дословную цитату. Между красивой редактурой и
верностью речи выбирай верность речи.
"""
