#!/usr/bin/env python3
"""Positive reasoning guidance blocks for Gemini prompts.

These blocks teach a repeatable intellectual and pastoral procedure rather than
merely imposing formatting bans. The core order is truth -> understanding ->
error correction -> assimilation -> response, with the balance adapted to the
actual genre and burden of the material.
"""
from __future__ import annotations


def _evidence_ladder(task: str) -> str:
    if task == "audio":
        return """\
ЛЕСТНИЦА УВЕРЕННОСТИ:
1. Явно звучит — формулируй прямо и привязывай к таймкоду.
2. Следует из нескольких частей речи — называй выводом из хода аргумента.
3. Внешний проверенный контекст — добавляй только если он проясняет услышанное.
4. Спорно, неизвестно или основано на одном намёке — не включай.
"""
    if task == "synopsis":
        return """\
ЛЕСТНИЦА ВЕРНОСТИ РЕЧИ:
1. Реальный порядок мысли, причинные связки и характерные формулировки автора.
2. Очистка оговорок, технического шума и пустых повторов.
3. Уплотнение без превращения речи в собственное богословское эссе.
4. Внешний контекст никогда не выдаётся за слова автора.
"""
    if task == "study":
        return """\
ЛЕСТНИЦА ИССЛЕДОВАТЕЛЬСКОЙ НАДЁЖНОСТИ:
1. Текст Писания и прямо заявленные тезисы материала.
2. Необходимые выводы из контекста, грамматики и хода аргумента.
3. Устоявшийся историко-богословский фон с ясной релевантностью.
4. Спорная позиция — только с честным обозначением границ и альтернатив.
5. Непроверенная цитата, страница или эффектная деталь — исключить.
"""
    if task == "reflection":
        return """\
ЛЕСТНИЦА ПАСТЫРСКОЙ ВЕРНОСТИ:
1. Сначала истина о Боге, Христе, Евангелии и тексте Писания.
2. Затем то, как эта истина исправляет понимание и разоблачает ложь сердца.
3. Затем соразмерный ответ веры через обязанности, отношения и средства благодати.
4. Не навязывай грех, диагноз, эмоцию или действие, которых материал не даёт.
"""
    return "Сначала установи источник утверждения, затем сделай вывод и только потом оформляй текст."


def _truth_first_order(task: str) -> str:
    if task not in {"audio", "study", "reflection"}:
        return ""
    common = """\
ИСТИНА ПРЕЖДЕ ПРАКТИКИ:
• Сначала установи, ЧТО именно материал утверждает как истину и на каком тексте
  Писания, контексте или аргументе это держится.
• Отдели библейское утверждение от иллюстрации, эмоционального эффекта и совета.
• Назови, что человек должен понять верно, а не только что он должен сделать.
• Покажи, какую ошибку, ложную предпосылку или поверхностное чтение исправляет истина.
• Только после понимания переходи к усвоению и ответу. Практика без основания
  превращается в технику, мораль или закон без Евангелия.
• Не добавляй искусственный application к каждой мысли: иногда верный плод —
  яснее увидеть Бога, точнее исповедовать истину, отказаться от ложного вывода,
  научиться читать текст или терпеливо удерживать напряжение.
"""
    if task == "audio":
        return common + """\
В первичном анализе зафиксируй внутренне: управляющую истину материала, какое
непонимание она исправляет и какой ответ действительно следует из неё. Распредели
это по существующим полям JSON, не добавляя новых ключей.
"""
    if task == "study":
        return common + """\
Study прежде всего помогает усвоить истину Писания: увидеть основание, контекст,
различения, границы и следствия. Практические советы здесь вторичны и допустимы
лишь для пояснения доктринального следствия, а не как самостоятельная рубрика.
"""
    return common + """\
Reflection также начинается не с «что делать», а с короткого, ясного усвоения:
какая истина должна стать новой рамкой мышления и почему она верна. Затем покажи,
как эта истина входит в совесть, желания, отношения, решения и молитву.
"""


def _adaptive_genre_balance(task: str) -> str:
    if task not in {"audio", "study", "reflection", "synopsis"}:
        return ""
    return """\
АДАПТАЦИЯ К ЖАНРУ — НЕ НАКЛАДЫВАЙ ОДИН ШАБЛОН:
• expository / doctrinal / catechetical — доминируют текст, определения,
  различения и логика; применение вырастает из них и не вытесняет их;
• apologetic / polemical — сначала точно изложи утверждение и сильнейшую версию
  возражения, затем основание ответа и только потом последствия;
• evangelistic — ясно раскрой Бога, грех, Христа, покаяние и веру; призыв не
  заменяет содержание Евангелия;
• practical / wisdom — назови управляющую библейскую истину и критерий мудрости,
  затем переходи к случаям, решениям, привычкам и последствиям;
• narrative / testimony — сохраняй историю и Божье действие; не насаждай
  искусственную систематику, но выдели истину, которую сам рассказ открывает;
• pastoral / comforting — основание утешения важнее эмоционального успокоения;
  покажи, что истинно о Боге и Его обетовании;
• Q&A / interview — раскрой не только ответ, но и предпосылку вопроса; не делай
  из осторожного ответа универсальную догму.

Баланс определяется реальным материалом. Богословская проповедь может почти не
содержать практических шагов; практическая всё равно не должна терять истину,
которая управляет советом.
"""


def _intellectual_workflow(task: str) -> str:
    common = """\
ИНТЕЛЛЕКТУАЛЬНЫЙ ХОД — ПЕРЕД НАПИСАНИЕМ:
• Сформулируй главный вопрос материала одним конкретным предложением.
• Назови управляющую истину и её основание.
• Назови исходную предпосылку или ложную интуицию, с которой спорит речь.
• Восстанови цепь: текст/основание → смысл → различение → следствие → ответ.
• Найди места, где меняется не тема, а способ видеть тему.
• Проверь сильную альтернативу: какой правдоподобный вывод здесь закрывается?
• Отдели вывод автора от собственного возможного домысливания.
"""
    if task == "synopsis":
        return common + """\
Для конспекта карта остаётся внутренней. В публикации передай ход речи, а не
список аналитических ярлыков. Причинные связки автора важнее красивых рубрик.
"""
    if task == "study":
        return common + """\
Для Study выбирай линзы, которые меняют понимание: контекст текста, ключевое
различение, доктринальное следствие, историческая полемика, перевод или лексика.
Линза без нового знания не является глубиной.
"""
    if task == "reflection":
        return common + """\
Для Reflection пройди путь: истина → усвоение → сопротивление → мудрый ответ.
Спроси: что истинно о Боге; что я должен начать видеть иначе; какая ложная опора
мешает; кого затрагивает ответ; какой шаг соответствует обязанностям и ограничениям.
"""
    return common


def _translation_and_original_method(task: str) -> str:
    if task not in {"audio", "study"}:
        return ""
    return """\
ПОЛОЖИТЕЛЬНЫЙ МЕТОД РАЗБОРА ПЕРЕВОДОВ И ОРИГИНАЛА:

Включай такой разбор только когда он меняет понимание текста, аргумента или
богословского следствия. Отсутствие содержательной развилки — нормальный результат;
не выжимай раздел ради полноты шаблона.

Сначала определи ТИП различия:
1. лексический выбор — разные допустимые значения одного слова;
2. грамматическая форма — время, вид, залог, число, синтаксическая связь;
3. структура предложения — к чему относится оборот или где стоит логический акцент;
4. степень явности — один перевод раскрывает подразумеваемое, другой сохраняет
   компактность или неоднозначность;
5. текстуальный вариант — переводы следуют разным чтениям рукописной традиции;
6. стилистическая передача — смысл тот же, меняются регистр, образ или плавность.

Затем объясняй в таком порядке:
• ОБЩАЯ ОСНОВА: что все сравниваемые переводы передают одинаково. Начинай с
  согласия, чтобы не создавать ложную драму.
• ТОЧКА РАСХОЖДЕНИЯ: одно конкретное слово, форма или связь — без обзора всего стиха.
• ПОЧЕМУ ВОЗНИКЛИ ВАРИАНТЫ: семантический диапазон, грамматика, рукописное чтение,
  различная степень буквальности или решение переводческой команды.
• ЧТО ДАЁТ КАЖДЫЙ ВАРИАНТ: не «хороший против плохого», а какую грань один делает
  явнее и что другой сохраняет точнее или осторожнее.
• ВЛИЯНИЕ НА АРГУМЕНТ: меняется ли доктринальный вывод, пастырский оттенок,
  временная перспектива, субъект действия, интенсивность или только формулировка.
• ВЕРДИКТ ПО СТЕПЕНИ: равнозначные варианты; один точнее в контексте; один
  возможен, но менее вероятен; либо действительно разные текстовые чтения.

ОБЪЯСНЕНИЕ ГРАММАТИКИ:
Не называй форму «продолжительным процессом» только потому, что английский
перевод использовал форму с -ing или русский — несовершенный вид. Покажи, какая
именно форма стоит в оригинале, что она обычно кодирует в этом контексте и чего
сама по себе НЕ доказывает. Вид действия, временная протяжённость и повторяемость
связаны, но не тождественны.

ЛЕКСИКА:
Не делай этимологию богословием. Значение определяется употреблением в данном
предложении, абзаце, книге и корпусе, а не суммой частей слова. Дай семантический
диапазон кратко, затем обоснуй контекстуальный выбор и покажи, какой неверный
вывод он предотвращает.

ТОН РАЗБОРА:
Пиши как проводник по решениям текста, а не как судья переводов. Разница обычно
дополняет картину; называй противоположностью только реальное несовместимое
чтение. Не создавай эффект «в Синодальном всё потеряно, а LSB наконец раскрывает
тайну». Сильный разбор делает читателя способнее самостоятельно видеть данные,
а не зависимее от громкого вердикта.
"""


def _learner_model(task: str) -> str:
    if task == "synopsis":
        return """\
МОДЕЛЬ ЧИТАТЕЛЯ:
После конспекта человек должен суметь восстановить исходный вопрос, управляющую
истину, повороты аргумента и финал речи. Не перегружай память повторными
определениями, одинаковыми заголовками и декоративной структурой.
"""
    if task == "study":
        return """\
МОДЕЛЬ УСВОЕНИЯ ИСТИНЫ:
Каждый раздел должен делать хотя бы одно:
1. ясно сформулировать истину и показать её основание в тексте;
2. дать различение, без которого истину легко исказить;
3. исправить правдоподобное заблуждение;
4. связать текст, доктрину и необходимое следствие;
5. показать, как читатель может сам проверить утверждение по Писанию;
6. помочь перенести способ чтения или различения в новый текст и спор.
Факт без связи не обучает; действие без истины не формирует зрелость.
"""
    if task == "reflection":
        return """\
МОДЕЛЬ УЧЕНИЧЕСТВА:
Читатель должен понять истину, суметь повторить её своими словами, увидеть, какую
ошибку она исправляет, распознать тот же духовный механизм в другой ситуации и
ответить верой. Не подменяй усвоение эмоциональным нажимом или списком действий.
"""
    if task == "audio":
        return """\
МОДЕЛЬ ДАЛЬНЕЙШЕГО ИСПОЛЬЗОВАНИЯ:
Поля анализа станут основой конспекта, Study и Reflection. Фиксируй не только
темы, но и истину, основание, ошибку, различение, причинность, перелом и следствие.
"""
    return "Текст должен менять структуру понимания, а не только сообщать содержание."


def _wisdom_grid(task: str) -> str:
    if task not in {"study", "reflection", "audio"}:
        return ""
    intro = """\
СЕТКА БИБЛЕЙСКОЙ МУДРОСТИ — ИСПОЛЬЗУЙ ТОЛЬКО РЕЛЕВАНТНОЕ:
• Бог и Его характер: какая истина о Нём управляет выводом?
• Писание: где основание, контекст и границы применения?
• Христос и Евангелие: не получается ли закон без Спасителя и благодати?
• Сердце: какое желание, страх, гордость, неверие или любовь движет человеком?
• Ближний и церковь: кто несёт последствия решения и кому нужна верность?
• Призвание: какие обязанности, власть, время и ограничения уже даны Богом?
• Средства благодати: Слово, молитва, церковь, исповедание, совет, послушание —
  без магических техник и мгновенных обещаний;
• Плод во времени: что это решение выращивает через неделю, год и поколение?
"""
    if task == "study":
        return intro + """\
Study использует сетку для обнаружения пропущенных следствий и границ, но
публикует только доказуемое. Не превращай каждую ось в обязательный раздел.
"""
    if task == "reflection":
        return intro + """\
Reflection соединяет истину, мотив, отношения и действие. Зрелый ответ может
требовать не активности, а ожидания, совета, покаяния, терпения или верности уже
данной обязанности.
"""
    return intro


def _anti_banality_gate(task: str) -> str:
    task_note = {
        "synopsis": "Сохрани конкретные тексты, сцены, контрасты и связки автора.",
        "study": "Каждый абзац содержит связь: текст → смысл → следствие или ошибка → причина → ответ.",
        "reflection": "Каждый ответ вырастает из истины и привязан к реальному сопротивлению и наблюдаемому шагу.",
        "audio": "Общие слова не годятся как исходные данные; фиксируй основание, механизм и следствие.",
    }.get(task, "Требуй конкретику, причинность и проверяемое следствие.")
    return f"""\
АНТИБАНАЛЬНЫЙ ФИЛЬТР:
1. Можно ли вставить предложение почти в любую проповедь? Если да — удалить или конкретизировать.
2. Есть ли новый факт, истина, различение, причина, следствие, критерий или действие? Если нет — удалить.
3. Заменяет ли эпитет «важный», «глубокий», «актуальный», «духовный» саму мысль? Раскрой мысль.
4. Есть ли пустая формула: «доверять Богу», «применять истину», «больше молиться»?
   Назови, какой истине доверять, против какой лжи, в какой ситуации и как это будет видно.
5. Повторяет ли абзац заголовок? Добавь основание или механизм либо убери абзац.
6. Звучит ли решение мудро только потому, что оно строгое или эмоциональное?
   Проверь библейское основание, соразмерность, обязанности и последствия.
7. Не перепрыгнул ли текст от стиха прямо к действию, не объяснив смысл стиха?

{task_note}
"""


def build_reasoning_first_block(task: str = "general") -> str:
    """Return a reusable reasoning-first instruction block."""
    task = (task or "general").strip().lower()
    if task == "audio":
        focus = (
            "Восстанови карту материала: жанр, главный вопрос, управляющую истину, "
            "основание, ложную предпосылку, ход аргумента, перелом, последствия и тон."
        )
    elif task == "synopsis":
        focus = (
            "Восстанови ход речи: откуда начинается вопрос, какая истина раскрывается, "
            "через какие различения идёт автор и к чему приводит слушателя."
        )
    elif task == "study":
        focus = (
            "Определи, какие исследовательские линзы помогут усвоить истину Писания: "
            "контекст, доктринальное различение, полемика, перевод или лексика."
        )
    elif task == "reflection":
        focus = (
            "Установи истину Писания прежде применения: что открывается о Боге, "
            "как это меняет понимание, какую ложь разрушает и какого ответа веры требует."
        )
    else:
        focus = "Сначала пойми внутреннюю логику материала, затем пиши результат."

    return f"""\
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
REASONING-FIRST — ИСТИНА, ПОНИМАНИЕ, УСВОЕНИЕ, ОТВЕТ
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

{focus}

{_evidence_ladder(task)}
{_truth_first_order(task)}
{_adaptive_genre_balance(task)}
{_intellectual_workflow(task)}
{_translation_and_original_method(task)}
{_learner_model(task)}
{_wisdom_grid(task)}
{_anti_banality_gate(task)}
Работай как внимательный богословский редактор. Простоту не маскируй
псевдоглубиной; богатство не обедняй ради одинаковой структуры.
"""


def build_synopsis_reasoning_note() -> str:
    """Backward-friendly named helper for Synopsis."""
    return build_reasoning_first_block("synopsis") + """\

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
СТЕПЕНЬ ДОСЛОВНОСТИ КОНСПЕКТА
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

Цель Synopsis — верная, подробная и читаемая передача речи, а не механическая
копия каждого слова и не краткий пересказ. Сохраняй весь смысловой ход,
управляющую истину, причинные связки, важные примеры, риторические повороты и
сильные формулировки. Разрешено убирать оговорки, пустые повторы и технический шум.
Не выдавай плотную парафразу за дословную цитату. Если сомневаешься между красивой
редактурой и верностью речи — выбирай верность речи.
"""
