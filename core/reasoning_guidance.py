#!/usr/bin/env python3
"""Positive reasoning guidance blocks for Gemini prompts.

The guidance is intentionally compact enough to remain usable inside large
prompts, but strong enough to move the model beyond formatting compliance.
It teaches a repeatable intellectual procedure: evidence, distinctions,
causality, biblical wisdom, learner transfer, and an anti-banality gate.
"""
from __future__ import annotations


def _evidence_ladder(task: str) -> str:
    if task == "audio":
        return """\
ЛЕСТНИЦА УВЕРЕННОСТИ:
1. Явно звучит — можно формулировать прямо и привязывать к таймкоду.
2. Следует из нескольких частей речи — формулируй как вывод из хода аргумента.
3. Внешний проверенный контекст — добавляй только если он реально проясняет услышанное.
4. Спорно, неизвестно или основано на одном намёке — не включай.
"""
    if task == "synopsis":
        return """\
ЛЕСТНИЦА ВЕРНОСТИ РЕЧИ:
1. Сохрани реальный порядок мысли, причинные связки и характерные формулировки.
2. Удали оговорки, технический шум и пустые повторы.
3. Сожми, но не улучшай автора до собственного богословского эссе.
4. Внешний контекст не должен становиться голосом автора.
"""
    if task == "study":
        return """\
ЛЕСТНИЦА ИССЛЕДОВАТЕЛЬСКОЙ НАДЁЖНОСТИ:
1. Текст Писания и прямо заявленные тезисы материала.
2. Необходимые выводы из контекста, грамматики и хода аргумента.
3. Устоявшийся историко-богословский фон с ясной релевантностью.
4. Спорная позиция — только с честным обозначением границ и альтернатив.
5. Непроверенная цитата, точная страница или эффектная деталь — исключить.
"""
    if task == "reflection":
        return """\
ЛЕСТНИЦА ПАСТЫРСКОЙ ВЕРНОСТИ:
1. Сначала то, что Бог открывает и совершает; затем ответ человека.
2. Затем конкретная ложная опора, страх, желание или привычка, вскрытая материалом.
3. Затем соразмерный шаг верности через обычные средства благодати, отношения и призвание.
4. Не навязывай грех, диагноз или драму, которых материал не даёт.
"""
    return "Сначала установи источник утверждения, затем делай вывод и только потом оформляй текст."


def _intellectual_workflow(task: str) -> str:
    common = """\
ИНТЕЛЛЕКТУАЛЬНЫЙ ХОД — ПЕРЕД НАПИСАНИЕМ:
• Сформулируй главный вопрос материала одним конкретным предложением.
• Назови исходную предпосылку или ложную интуицию, с которой спорит речь.
• Восстанови причинную цепь: основание → различение → следствие → ответ.
• Найди 1–3 места, где меняется не тема, а способ видеть тему.
• Проверь альтернативу: какой правдоподобный, но неверный вывод здесь закрывается?
• Отдели сильный вывод автора от собственного возможного домысливания.
"""
    if task == "synopsis":
        return common + """\
Для конспекта эта карта остаётся внутренней. В публикации передай ход речи,
а не список аналитических ярлыков. Причинные связки автора важнее красивых рубрик.
"""
    if task == "study":
        return common + """\
Для Study выбери только те линзы, которые действительно что-то открывают:
контекст текста, ключевое различение, доктринальное следствие, историческая
полемика, переводческая развилка, лексическая функция. Линза без нового знания
не является глубиной.
"""
    if task == "reflection":
        return common + """\
Для Reflection переведи аргумент не сразу в «сделай», а через четыре вопроса:
что здесь истинно о Боге; что это разоблачает во мне; кого затрагивает мой ответ;
какой верный шаг возможен в моих реальных обязанностях и ограничениях.
"""
    return common


def _learner_model(task: str) -> str:
    if task == "synopsis":
        return """\
МОДЕЛЬ ЧИТАТЕЛЯ:
Конспект должен позволить человеку восстановить ход речи без видео. После чтения
он должен уметь назвать исходный вопрос, 2–4 поворота аргумента и финальный призыв.
Не перегружай память одинаковыми заголовками, повторными определениями и декором.
"""
    if task == "study":
        return """\
МОДЕЛЬ ОБУЧЕНИЯ:
Каждый раздел должен делать хотя бы одно из пяти:
1. дать различение, которого читатель раньше не видел;
2. исправить правдоподобное заблуждение;
3. связать текст, доктрину и следствие;
4. показать, как проверить утверждение по Писанию;
5. помочь перенести принцип в новый текст или спор.
Простое сообщение факта без изменения понимания — справка, а не обучение.
"""
    if task == "reflection":
        return """\
МОДЕЛЬ УЧЕНИЧЕСТВА:
Читатель должен не только почувствовать, но и научиться распознавать тот же
духовный механизм в другой ситуации. Дай признаки распознавания, критерий
различения и соразмерный следующий шаг. Не подменяй научение эмоциональным нажимом.
"""
    if task == "audio":
        return """\
МОДЕЛЬ ДАЛЬНЕЙШЕГО ИСПОЛЬЗОВАНИЯ:
Поля анализа станут основой конспекта, Study и Reflection. Поэтому фиксируй не
только темы, но и предпосылки, различения, причинные связи, переломы и последствия.
"""
    return "Текст должен менять структуру понимания читателя, а не только сообщать содержание."


def _wisdom_grid(task: str) -> str:
    if task not in {"study", "reflection", "audio"}:
        return ""
    intro = """\
СЕТКА БИБЛЕЙСКОЙ МУДРОСТИ — ИСПОЛЬЗУЙ ТОЛЬКО РЕЛЕВАНТНЫЕ ОСИ:
• Бог и Его характер: какая истина о Нём управляет выводом?
• Писание: на каком тексте держится утверждение и что ограничивает его применение?
• Сердце: какое желание, страх, гордость, неверие или любовь движет человеком?
• Ближний и церковь: кто несёт последствия решения, кому нужна верность, терпение или истина?
• Призвание и обстоятельства: какие обязанности, власть, время и ограничения Бог уже дал?
• Средства благодати: Слово, молитва, церковь, исповедание, совет, послушание — без магических техник.
• Плод во времени: что решение выращивает через неделю, год и поколение?
• Христос и Евангелие: не превращается ли применение в закон без Спасителя и благодати?
"""
    if task == "study":
        return intro + """\
Study не обязан превращать каждую ось в раздел. Используй сетку, чтобы увидеть
пропущенные следствия и границы, а затем публикуй только доказуемое и полезное.
"""
    if task == "reflection":
        return intro + """\
Reflection должен соединять истину, мотив, отношения и действие. Не своди мудрость
к самонаблюдению: зрелый ответ часто требует разговора, ожидания, совета, покаяния,
терпения или исполнения уже данных обязанностей.
"""
    return intro


def _anti_banality_gate(task: str) -> str:
    task_note = {
        "synopsis": "Сохрани конкретные существительные, сцены, тексты, контрасты и формулировки автора.",
        "study": "Каждый абзац обязан содержать проверяемую связь: текст → смысл → следствие или ошибка → причина → ответ.",
        "reflection": "Каждое применение привяжи к сцене/тезису материала, реальному сопротивлению и наблюдаемому шагу.",
        "audio": "Общие слова не годятся как исходные данные для следующих страниц; фиксируй механизм и следствие.",
    }.get(task, "Требуй конкретику, причинность и проверяемое следствие.")
    return f"""\
АНТИБАНАЛЬНЫЙ ФИЛЬТР — ПЕРЕД ОТВЕТОМ:
1. Можно ли вставить предложение почти в любую проповедь без изменений? Если да — удалить или конкретизировать.
2. Есть ли в нём новый факт, различение, причина, следствие, критерий или действие? Если нет — удалить.
3. Заменяет ли слово «важный», «глубокий», «актуальный», «духовный рост» саму мысль? Раскрой мысль вместо эпитета.
4. Есть ли ложная торжественность без предмета: «это призывает нас доверять Богу», «нам нужно применять истину», «следует больше молиться»? Назови чему доверять, в какой ситуации, против какой ложной опоры и как это будет видно.
5. Не повторяет ли абзац заголовок другими словами? Если повторяет — добавь механизм или убери абзац.
6. Не звучит ли решение мудро лишь потому, что оно строгое, эмоциональное или богословски насыщенное? Проверь соразмерность, контекст и последствия.

{task_note}
"""


def build_reasoning_first_block(task: str = "general") -> str:
    """Return a reusable reasoning-first instruction block."""
    task = (task or "general").strip().lower()
    if task == "audio":
        focus = (
            "Сначала восстанови карту материала: жанр, главный вопрос, скрытую предпосылку, "
            "ход аргумента, ключевые тексты, переломные моменты, последствия и пастырский тон."
        )
    elif task == "synopsis":
        focus = (
            "Сначала восстанови ход речи автора: откуда он начинает, какую проблему называет, "
            "через какие различения идёт, где меняет рамку и к чему приводит слушателя."
        )
    elif task == "study":
        focus = (
            "Сначала определи, какие 2–4 исследовательские линзы действительно изменят понимание: "
            "контекст текста, доктринальное различение, историческая полемика, перевод или лексика."
        )
    elif task == "reflection":
        focus = (
            "Сначала установи пастырский нерв: что истинно о Боге, какую ложную опору ломает материал, "
            "какого ответа веры требует и через какие обычные средства этот ответ созревает."
        )
    else:
        focus = "Сначала пойми внутреннюю логику материала, затем пиши результат."

    return f"""\
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
REASONING-FIRST — СНАЧАЛА ПОНИМАНИЕ, ПОТОМ ФОРМА
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

{focus}

{_evidence_ladder(task)}
{_intellectual_workflow(task)}
{_learner_model(task)}
{_wisdom_grid(task)}
{_anti_banality_gate(task)}
Работай как внимательный богословский редактор, который помогает материалу
раскрыться, а не зажимает его шаблоном. Простоту не маскируй псевдоглубиной;
богатство не обедняй ради ровной структуры.
"""


def build_synopsis_reasoning_note() -> str:
    """Backward-friendly named helper for Synopsis."""
    return build_reasoning_first_block("synopsis") + """\

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
СТЕПЕНЬ ДОСЛОВНОСТИ КОНСПЕКТА
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

Цель Synopsis — сжатая стенограмма, а не пересказ. Сохраняй авторский ход,
лексику, причинные связки, риторические повороты, обращения к слушателям и сильные
формулировки. Разрешено убирать оговорки, пустые повторы и технический шум.
Если сомневаешься между красивой редактурой и верностью речи — выбирай верность речи.
Не выдавай плотную парафразу за дословную цитату.
"""
