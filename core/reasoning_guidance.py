#!/usr/bin/env python3
"""Positive reasoning guidance blocks for Gemini prompts.

These blocks are deliberately framed as permissions and reasoning procedure, not
as another wall of bans. They are injected before task-specific constraints so
Gemini spends more effort understanding the material and less effort navigating
negative phrasing.
"""
from __future__ import annotations


def _evidence_ladder(task: str) -> str:
    if task == "audio":
        return """\
Лестница уверенности для полей JSON:
• high — явно звучит в аудио или устойчиво подтверждено несколькими таймкодами;
• medium — следует из хода речи, но формулируй осторожнее;
• low — оставь пустым/не включай. Лучше пустое поле, чем уверенная догадка.
"""
    if task == "synopsis":
        return """\
Лестница верности речи:
• сначала дословный ход автора и его формулировки;
• затем лёгкая очистка оговорок, пустых повторов и технических пауз;
• затем структура sections. Не превращай это в редакторскую статью.
"""
    if task == "study":
        return """\
Лестница исследовательской ценности:
• сперва тексты Писания и реальные термины из материала;
• затем доктринальные связи, которые помогают понять аргумент;
• затем источники — только если можешь объяснить, почему источник относится именно к этому материалу.
"""
    if task == "reflection":
        return """\
Лестница пастырского применения:
• сперва тон и нерв самого материала;
• затем конкретная диагностика сердца;
• затем молитвенный отклик и шаги верности. Не усиливай драму сверх тона материала.
"""
    return "Сначала понимание материала, затем форма ответа."


def build_reasoning_first_block(task: str = "general") -> str:
    """Return a compact positive reasoning-first instruction block."""
    task = (task or "general").strip().lower()
    if task == "audio":
        focus = (
            "Сначала восстанови карту материала: жанр, главный конфликт, ход мысли, "
            "ключевые тексты, переломные моменты и пастырский тон. Затем заполняй поля JSON."
        )
    elif task == "synopsis":
        focus = (
            "Сначала восстанови ход речи автора: откуда он начинает, через какие узлы идёт, "
            "где делает поворот и к чему приводит слушателя. Потом оформи sections."
        )
    elif task == "study":
        focus = (
            "Сначала определи, какие 2–4 исследовательские линзы реально раскрывают этот материал: "
            "текст Писания, доктрина, исторический фон, языки оригинала, богословская полемика."
        )
    elif task == "reflection":
        focus = (
            "Сначала почувствуй пастырский нерв материала: где он утешает, где обличает, "
            "какую ложную опору ломает и к какой верности зовёт."
        )
    else:
        focus = "Сначала пойми внутреннюю логику материала, затем пиши результат."

    return f"""\
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
РАЗРЕШЕНО И ЖЕЛАТЕЛЬНО — REASONING-FIRST
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

{focus}

{_evidence_ladder(task)}

Работай как внимательный богословский редактор, который помогает материалу
раскрыться, а не зажимает его шаблоном. Если материал богатый — покажи богатство.
Если материал простой — не имитируй глубину искусственно.

Проверенный контекст разрешён, когда он служит уже звучащей мысли: известный
библейский фон, значение оригинального слова, общеизвестный историко-богословский
факт, связь с конфессиональной рамкой. Контекст не должен заменять речь автора.

Для языков оригинала не делай словарную карточку ради карточки. Покажи функцию
слова в аргументе: где оно стоит, что уточняет, какую ложную развилку закрывает,
почему без него читатель понял бы текст беднее.
"""


def build_synopsis_reasoning_note() -> str:
    """Backward-friendly named helper for Synopsis."""
    return build_reasoning_first_block("synopsis") + """\

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
СТЕПЕНЬ ДОСЛОВНОСТИ КОНСПЕКТА
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

Цель Synopsis — сжатая стенограмма, а не пересказ. Сохраняй 99% авторского хода:
лексику, порядок мысли, риторические повороты, обращения к слушателям, сильные
формулировки. Разрешено убирать оговорки, пустые повторы и технический шум.
Если сомневаешься между красивой редактурой и верностью речи — выбирай верность речи.
"""
